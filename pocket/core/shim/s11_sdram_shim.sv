// GPL-2.0-or-later. `sdram` for SYSTEM11.sv on the Pocket: the MiSTer sdram.sv port list in front of the MIT psx_sdram_ctrl
// (single 16-bit chip, CAS latency 3 at 101.6 MHz). SYSTEM11.sv instantiates `sdram sdram (...)` unchanged; the debug and
// tuning ports of the MiSTer module (phase-shifted clocks, page mode, JTAG taps) are accepted and ignored.
`default_nettype none
module sdram (
    input  wire         init,
    input  wire         clk,
    input  wire         clk_sdramclk,
    input  wire         clk_dqcap,
    input  wire         clk_base,
    input  wire         SDRAM_EN,
    inout  wire [15:0]  SDRAM_DQ,
    output wire [12:0]  SDRAM_A,
    output wire         SDRAM_DQML,
    output wire         SDRAM_DQMH,
    output wire [1:0]   SDRAM_BA,
    output wire         SDRAM_nCS,
    output wire         SDRAM_nWE,
    output wire         SDRAM_nRAS,
    output wire         SDRAM_nCAS,
    output wire         SDRAM_CKE,
    output wire         SDRAM_CLK,
    input  wire         refreshForce,
    input  wire         pagemode_en,
    output wire         ram_idle,
    input  wire [26:0]  ch1_addr,
    output wire [127:0] ch1_dout,
    output wire [31:0]  ch1_dout32,
    input  wire [15:0]  ch1_din,
    input  wire         ch1_req,
    input  wire         ch1_rnw,
    input  wire         ch1_dma,
    input  wire [1:0]   ch1_cntDMA,
    input  wire         ch1_cache,
    output wire         ch1_ready,
    output wire [3:0]   cache_wr,
    output wire [31:0]  cache_data,
    output wire [7:0]   cache_addr,
    output wire         dma_wr,
    output wire         dma_reqprocessed,
    output wire [31:0]  dma_data,
    input  wire [26:0]  ch2_addr,
    output wire [31:0]  ch2_dout,
    input  wire [31:0]  ch2_din,
    input  wire         ch2_req,
    input  wire         ch2_rnw,
    input  wire [3:0]   ch2_be,
    output wire         ch2_ready,
    input  wire [26:0]  ch3_addr,
    output wire [31:0]  ch3_dout,
    input  wire [31:0]  ch3_din,
    input  wire         ch3_req,
    input  wire         ch3_rnw,
    input  wire [3:0]   ch3_be,
    output wire         ch3_ready,
    input  wire [26:0]  dmafifo_adr,
    input  wire [31:0]  dmafifo_data,
    input  wire         dmafifo_empty,
    output wire         dmafifo_read,
    output wire         dbg_pm_hit,
    output wire         dbg_pm_open,
    output wire         dbg_pm_pre,
    output wire [8:0]   dbg_sdram,
    output wire [7:0]   dbg_drd1
);
    assign dbg_pm_hit = 1'b0, dbg_pm_open = 1'b0, dbg_pm_pre = 1'b0, dbg_sdram = 9'd0, dbg_drd1 = 8'd0;

    psx_sdram_ctrl #(.SINGLE_CHIP(1), .CAS_LATENCY(3)) controller (
        .init(init), .clk(clk), .clk_base(clk_base), .SDRAM_EN(SDRAM_EN),
        .SDRAM_DQ(SDRAM_DQ), .SDRAM_A(SDRAM_A), .SDRAM_DQML(SDRAM_DQML), .SDRAM_DQMH(SDRAM_DQMH), .SDRAM_BA(SDRAM_BA),
        .SDRAM_nCS(SDRAM_nCS), .SDRAM_nWE(SDRAM_nWE), .SDRAM_nRAS(SDRAM_nRAS), .SDRAM_nCAS(SDRAM_nCAS),
        .SDRAM_CKE(SDRAM_CKE), .SDRAM_CLK(SDRAM_CLK),
        .refreshForce(refreshForce), .ram_idle(ram_idle),
        .ch1_addr(ch1_addr), .ch1_dout(ch1_dout), .ch1_dout32(ch1_dout32), .ch1_din(ch1_din), .ch1_req(ch1_req),
        .ch1_rnw(ch1_rnw), .ch1_dma(ch1_dma), .ch1_cntDMA(ch1_cntDMA), .ch1_cache(ch1_cache), .ch1_ready(ch1_ready),
        .cache_wr(cache_wr), .cache_data(cache_data), .cache_addr(cache_addr),
        .dma_wr(dma_wr), .dma_reqprocessed(dma_reqprocessed), .dma_data(dma_data),
        .ch2_addr(ch2_addr), .ch2_dout(ch2_dout), .ch2_din(ch2_din), .ch2_req(ch2_req), .ch2_rnw(ch2_rnw),
        .ch2_be(ch2_be), .ch2_ready(ch2_ready),
        .ch3_addr(ch3_addr), .ch3_dout(ch3_dout), .ch3_din(ch3_din), .ch3_req(ch3_req), .ch3_rnw(ch3_rnw),
        .ch3_be(ch3_be), .ch3_ready(ch3_ready),
        .dmafifo_adr(dmafifo_adr), .dmafifo_data(dmafifo_data), .dmafifo_empty(dmafifo_empty), .dmafifo_read(dmafifo_read)
    );
endmodule
`default_nettype wire
